"""Bundles: content-addressed candidates, and how a recipe + bundle becomes a server command.

Layout of a bundle directory:
  manifest.json      {"config_delta": {...}, "env": {...}, "overlays": {"<module/file.py>": "overlays/<...>"},
                      "kernels": ["kernels/<...>"], "drafter": "<abs path or null>", "note": "...",
                      "recipe_id": "...", "created_by": "..."}
  overlays/...       full replacement source files for files inside the recipe's venv site-packages
  kernels/...        kernel sources the overlays may import (put on PYTHONPATH)
The bundle hash is sha256 over the manifest's canonical JSON plus every file's path and bytes (never mtimes).

serve_command() is shared by the quick bench and (if core wants it) the gate, so both run a candidate the
same way. Overlays are applied by a sitecustomize import hook placed first on PYTHONPATH; that reaches
vLLM's spawned worker processes too, because they inherit the environment.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

MANIFEST = "manifest.json"


def canon(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"))


def hash_dir(root: Path) -> str:
    """sha256 over every file's relative path and bytes (symlinks by target). Skips .hook/ (generated)."""
    h = hashlib.sha256()
    root = Path(root)
    items = []
    for p in root.rglob("*"):
        rel = p.relative_to(root).as_posix()
        if rel.startswith(".hook/") or rel == ".hook":
            continue
        if p.is_symlink() or p.is_file():
            items.append((rel, p))
    for rel, p in sorted(items):
        if p.is_symlink():
            h.update(b"L" + rel.encode() + b"\0" + os.readlink(p).encode())
            continue
        h.update(b"F" + rel.encode() + b"\0")
        with open(p, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
    return h.hexdigest()


def hash_files(files: dict[str, bytes]) -> str:
    """Same digest hash_dir() computes for a directory holding exactly these files (relative posix paths)."""
    h = hashlib.sha256()
    for rel in sorted(files):
        h.update(b"F" + rel.encode() + b"\0")
        h.update(files[rel])
    return h.hexdigest()


def normalize_flag(k: str) -> str:
    k = k.strip()
    if not k.startswith("--"):
        k = "--" + k.lstrip("-")
    return k.replace("_", "-")


def normalize_delta(delta: dict | None) -> dict:
    return {normalize_flag(k): v for k, v in (delta or {}).items()}


def args_to_dict(args) -> dict:
    """Recipe serve args (list like ['--a', '1', '--flag'] or a dict) into an ordered flag -> value dict."""
    if isinstance(args, dict):
        return {normalize_flag(k): v for k, v in args.items()}
    out: dict = {}
    i = 0
    args = list(args or [])
    while i < len(args):
        a = str(args[i])
        if a.startswith("--"):
            if "=" in a:
                k, v = a.split("=", 1)
                out[normalize_flag(k)] = v
            elif i + 1 < len(args) and not str(args[i + 1]).startswith("--"):
                out[normalize_flag(a)] = args[i + 1]
                i += 1
            else:
                out[normalize_flag(a)] = True
        else:
            out.setdefault("_positional", []).append(a)
        i += 1
    return out


def dict_to_args(d: dict) -> list[str]:
    out = [str(x) for x in d.get("_positional", [])]
    for k, v in d.items():
        if k == "_positional" or v is None or v is False:
            continue
        if v is True:
            out.append(k)
        elif isinstance(v, (dict, list)):
            out += [k, json.dumps(v)]
        else:
            out += [k, str(v)]
    return out


def merged_args(serve_args, delta: dict | None) -> list[str]:
    d = args_to_dict(serve_args)
    for k, v in normalize_delta(delta).items():
        if v is None or v is False:
            d.pop(k, None)
        else:
            d[k] = v
    return dict_to_args(d)


SITECUSTOMIZE = '''\
# generated by forge.tools.bundle: redirect selected module files to bundle overlays
import importlib.abc, importlib.util, json, os, sys
_MAP = json.loads(os.environ.get("FORGE_OVERLAY_MAP", "{}"))
class _Finder(importlib.abc.MetaPathFinder):
    def find_spec(self, name, path=None, target=None):
        f = _MAP.get(name)
        if not f:
            return None
        is_pkg = f.endswith("__init__.py")
        spec = importlib.util.spec_from_file_location(
            name, f, submodule_search_locations=None if not is_pkg else None)
        if spec is None:
            return None
        if is_pkg:
            # keep the original package directory as the search path so siblings still import
            for p in sys.meta_path:
                if p is self or not hasattr(p, "find_spec"):
                    continue
                try:
                    orig = p.find_spec(name, path, target)
                except Exception:
                    orig = None
                if orig is not None:
                    spec.submodule_search_locations = orig.submodule_search_locations
                    break
        return spec
if _MAP:
    sys.meta_path.insert(0, _Finder())
'''


def module_name(rel: str) -> str:
    rel = rel.replace("\\", "/")
    if rel.endswith("/__init__.py"):
        rel = rel[: -len("/__init__.py")]
    elif rel.endswith(".py"):
        rel = rel[:-3]
    return rel.replace("/", ".")


def load_manifest(bundle_dir: str | Path) -> dict:
    return json.loads((Path(bundle_dir) / MANIFEST).read_text())


def serve_command(python: str, model: str, serve_args, bundle_dir: str | Path | None, port: int,
                  config_delta: dict | None = None, env_delta: dict | None = None,
                  hook_dir: str | Path | None = None) -> tuple[list[str], dict]:
    """argv + extra env for `vllm serve` of a recipe with an optional bundle and/or config delta."""
    delta = dict(config_delta or {})
    env = dict(env_delta or {})
    if bundle_dir:
        m = load_manifest(bundle_dir)
        delta = {**normalize_delta(m.get("config_delta")), **normalize_delta(delta)}
        env = {**(m.get("env") or {}), **env}
        overlays = m.get("overlays") or {}
        paths = []
        if overlays:
            hook = Path(hook_dir or Path(bundle_dir) / ".hook")
            hook.mkdir(parents=True, exist_ok=True)
            (hook / "sitecustomize.py").write_text(SITECUSTOMIZE)
            env["FORGE_OVERLAY_MAP"] = json.dumps(
                {module_name(rel): str((Path(bundle_dir) / f).resolve()) for rel, f in overlays.items()})
            paths.append(str(hook))
        if m.get("kernels"):
            paths.append(str((Path(bundle_dir) / "kernels").resolve()))
        if paths:
            env["PYTHONPATH"] = os.pathsep.join(paths + ([env["PYTHONPATH"]] if env.get("PYTHONPATH") else []))
    args = merged_args(serve_args, delta)
    args = [a for a in args]
    d = args_to_dict(args)
    d.pop("--port", None)
    d.pop("--host", None)
    model_pos = d.pop("_positional", None)
    argv = [python, "-m", "vllm.entrypoints.cli.main", "serve", (model_pos or [model])[0]]
    argv += dict_to_args(d) + ["--host", "127.0.0.1", "--port", str(port)]
    return argv, env
